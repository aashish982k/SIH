// Link incidents back to their wells (done at runtime to avoid circular refs)
export function getIncidentsForWell(wellId: string): Incident[] {
  return MOCK_INCIDENTS.filter(i => i.wellId === wellId);
}

export function getIncidentsByType(type: IncidentType): Incident[] {
  return MOCK_INCIDENTS.filter(i => i.type === type);
}

export function getIncidentsBySeverity(severity: RiskLevel): Incident[] {
  return MOCK_INCIDENTS.filter(i => i.severity === severity);
}
